// Precompile an optimized regex alternation for fast single-pass matching
const KANJI_MAP: Record<string, string> = Object.fromEntries(KANJI_RUBY_DICTIONARY)
const KANJI_REGEX = new RegExp(
  KANJI_RUBY_DICTIONARY.map(([word]) => word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'),
  'g',
)

/**
 * Annotates plain Japanese text with [漢字|かんじ] ruby syntax.
 * If text already contains [base|ruby] segments, it preserves them.
 */
export function annotateRuby(text: string): string {
  if (!text) return ''

  // Split on existing [base|ruby] bracket segments so we don't double-annotate
  const parts = text.split(/(\[[^|[\]]+\|[^|[\]]+\])/g)

  return parts
    .map((part) => {
      // If this part is already a ruby bracket, leave untouched
      if (part.startsWith('[') && part.endsWith(']') && part.includes('|')) {
        return part
      }
      // Replace matching kanji words using single-pass regex
      return part.replace(KANJI_REGEX, (match) => KANJI_MAP[match] ?? match)
    })
    .join('')
}
